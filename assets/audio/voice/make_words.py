"""Extend the bundled LJ Speech voice for dynamic radio readouts.
Uses the same offline environment/model as make_voice.py. Nothing is synthesized at runtime.
  python make_words.py MODEL --root REPOSITORY
"""
import argparse
import sys
sys.dont_write_bytecode = True
import os
from pathlib import Path
import re
import subprocess
import tempfile
import wave

from piper import PiperVoice
from make_voice import render, trimmed, levelled, save


def vocabulary(root):
    words = set('zero one two three four five six seven eight nine ten eleven twelve thirteen fourteen fifteen sixteen seventeen eighteen nineteen twenty thirty forty fifty sixty seventy eighty ninety hundred thousand million billion minus point percent kilometres metres seconds minutes degrees north south east west bearing heading latitude longitude local time temperature a signal right here faint clear strong wind speed weather station radio report advisory'.split())
    words.update(chr(i) for i in range(ord('a'), ord('z') + 1))
    fragments = set()
    for name in ['game/radio/transmissions.gd', 'game/radio/advisories.gd', 'game/radio/radio.gd',
                 'game/devices/catalog.gd', 'game/radio/city.gd', 'game/radio/radio_speech.gd']:
        source = (root / name).read_text()
        for quoted in re.findall(r'"((?:\\.|[^"\\])*)"', source):
            if 'res://' in quoted or '\\' in quoted:
                continue
            for part in re.split(r'%[-+\d.]*[dsf]|\{[ab]\}|\d+(?:\.\d+)?|[·.!?:;]|//', quoted):
                tokens = re.findall(r'[a-z]+', part.lower())
                words.update(tokens)
                if 2 <= len(tokens) <= 10 and '_' not in part and '=' not in part:
                    fragments.add(' '.join(tokens))
    # Context for the most frequent instrument phrases.
    fragments.update(['weather station', 'local time', 'metres a second', 'take shelter', 'weather advisory',
                      'right here', 'a signal', 'from the', 'temperature', 'survey log', 'net control'])
    return sorted(words | fragments)


def pack(root, pieces, entries, rate):
    spans = {}
    offset = 0
    with wave.open(str(root / 'assets/audio/voice/word_bank.wav'), 'wb') as bank:
        bank.setnchannels(1)
        bank.setsampwidth(2)
        bank.setframerate(rate)
        for phrase in entries:
            path = pieces / (phrase.replace(' ', '_') + '.ogg')
            data = subprocess.check_output(['ffmpeg', '-loglevel', 'error', '-i', str(path),
                                            '-f', 's16le', '-ac', '1', '-ar', str(rate), '-'])
            bank.writeframesraw(data)
            spans[phrase] = (offset, offset + len(data))
            offset += len(data)
    manifest = ['class_name VoiceWords', 'extends RefCounted',
                '## Generated by assets/audio/voice/make_words.py; same bundled LJ Speech voice.',
                'const BANK = preload("res://assets/audio/voice/word_bank.wav")', 'const SPANS := {']
    manifest.extend(f'\t"{phrase}": Vector2i({lo}, {hi}),' for phrase, (lo, hi) in spans.items())
    manifest += ['}', 'static var _tracks := {}', '', '',
                'static func track(word: String) -> AudioStreamWAV:',
                '\tif not _tracks.has(word):', '\t\tvar span: Vector2i = SPANS[word]',
                '\t\tvar clip := AudioStreamWAV.new()', '\t\tclip.format = BANK.format',
                '\t\tclip.mix_rate = BANK.mix_rate', '\t\tclip.stereo = false',
                '\t\tclip.data = BANK.data.slice(span.x, span.y)', '\t\t_tracks[word] = clip',
                '\treturn _tracks[word]']
    (root / 'game/radio/voice_words.gd').write_text('\n'.join(manifest) + '\n')
    print(f'{len(entries)} bundled words and fragments packed into one {offset / 1e6:.1f} MB bank', flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('model')
    parser.add_argument('--root', type=Path, required=True)
    parser.add_argument('--cache', type=Path)
    args = parser.parse_args()
    if hasattr(os, 'sched_getaffinity'):
        os.sched_setaffinity(0, sorted(os.sched_getaffinity(0))[:2])
    voice = PiperVoice.load(args.model, include_alignments=True)
    rate = voice.config.sample_rate
    with tempfile.TemporaryDirectory() as temporary:
        pieces = args.cache or Path(temporary)
        pieces.mkdir(parents=True, exist_ok=True)
        entries = vocabulary(args.root)
        for i, phrase in enumerate(entries):
            path = pieces / (phrase.replace(' ', '_') + '.ogg')
            if not path.exists():
                audio, voiced = trimmed(render(voice, phrase + '.'), rate)
                save(str(path), levelled(audio, voiced), rate)
            if i % 100 == 0:
                print(f'{i}/{len(entries)} {phrase}', flush=True)
        pack(args.root, pieces, entries, rate)


if __name__ == '__main__':
    main()
